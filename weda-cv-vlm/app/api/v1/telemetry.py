"""GET /v1/telemetry/recent + SSE /v1/telemetry/stream — per-query attribution.

Reads from the process-wide TelemetryStore (modules/telemetry.py) so
any consumer's per-query cost view sees every Tier-3 query the
pipeline executed.
"""

from __future__ import annotations

import asyncio
import json
from typing import Any, Dict, List, Optional

from fastapi import APIRouter, Depends
from pydantic import BaseModel, Field

try:
    from sse_starlette.sse import EventSourceResponse
    _HAS_SSE = True
except ImportError:
    _HAS_SSE = False

from app.api.v1._deps import PipelineHandle, require_handle
from app.modules.telemetry import get_store

router = APIRouter(prefix="/telemetry", tags=["telemetry"])


class TelemetryRecord(BaseModel):
    id: str = Field(..., description="Unique query id (12-char hex).")
    started_ts: float = Field(..., description="Epoch seconds when the query was accepted.")
    ended_ts: float = Field(0.0, description="Epoch seconds when the query finalised. 0 while still running.")
    wall_ms: float = Field(0.0, description="End-to-end wall time in milliseconds (token streaming included).")
    query: str = Field("", description="The user-facing query text.")
    source: str = Field("unknown", description='Origin of the query: e.g. `"http"`, `"keyboard"`, internal subsystem name.')
    request_id: str = Field("", description="Correlated request id when the query came from an HTTP entry point.")
    gpu_util_peak_pct: float = Field(0.0, description="Peak GPU utilisation during the query, 0-100.")
    uma_used_gb_start: float = Field(0.0, description="UMA in use when the query started, in GB.")
    uma_used_gb_peak: float = Field(0.0, description="Peak UMA in use during the query, in GB.")
    uma_used_gb_end: float = Field(0.0, description="UMA in use when the query finished, in GB.")
    cpu_pct_peak: float = Field(0.0, description="Peak process CPU utilisation, 0-100.")
    rss_mb_peak: float = Field(0.0, description="Peak resident-set size of the process in MB.")
    temperature_c_peak: float = Field(0.0, description="Peak GPU temperature during the query, in Celsius.")
    power_w_peak: float = Field(0.0, description="Peak board power draw in watts. 0 on hosts without power monitoring.")
    power_w_mean: float = Field(0.0, description="Mean board power across the live samples, in watts.")
    energy_j: float = Field(0.0, description="Approximate energy consumed in joules (mean power × wall_s).")
    cost_usd: float = Field(0.0, description="Estimated cost in USD using `tariff_usd_per_kwh` from config (default $0.12/kWh).")
    tokens_generated: int = Field(0, description="Total tokens generated by the VLM for this query.")
    tok_per_sec: float = Field(0.0, description="Tokens-per-second (= tokens_generated / wall_s).")
    tools_called: List[str] = Field(default_factory=list, description="Tool names called during this query.")
    factcheck_verified: int = Field(0, description="Fact-check claims with verdict `verified`. 0 when no fact-check ran.")
    factcheck_unverifiable: int = Field(0, description="Fact-check claims with verdict `unverifiable`.")
    factcheck_contradicted: int = Field(0, description="Fact-check claims with verdict `contradicted`.")
    success: bool = Field(True, description="True when the query completed without raising.")
    error: Optional[str] = Field(None, description="Error message when `success=false`. Null otherwise.")


class TelemetryRecentResponse(BaseModel):
    queries: List[TelemetryRecord] = Field(..., description="Recent query records, newest first. Capped at `limit` (default 50).")


@router.get(
    "/recent",
    response_model=TelemetryRecentResponse,
    summary="Recent per-query telemetry records, newest first",
    description=(
        "Each record carries wall time, GPU utilisation peak, UMA "
        "delta, CPU peak, thermal peak, power peak, energy (J), "
        "estimated cost, tokens generated, tools called, fact-check "
        "verdict mix, success/error. Bounded ring buffer."
    ),
)
async def telemetry_recent(
    limit: int = 50,
    handle: PipelineHandle = Depends(require_handle),
) -> TelemetryRecentResponse:
    return TelemetryRecentResponse(
        queries=[TelemetryRecord(**r.to_dict()) for r in get_store().recent(limit)],
    )


@router.get(
    "/stream",
    summary="Live per-query telemetry (SSE)",
    description="One `query` event per QueryRecord finalisation. `data` field is a JSON-encoded TelemetryRecord. Subscriber queue bounded at 200.",
    include_in_schema=False,
    responses={
        200: {
            "description": "SSE stream. Each event is `query` with a JSON-encoded TelemetryRecord in `data`.",
            "content": {"text/event-stream": {}},
        }
    },
)
async def telemetry_stream():
    if not _HAS_SSE:
        return {"error": "sse-starlette not installed"}
    store = get_store()
    queue: asyncio.Queue = asyncio.Queue(maxsize=200)

    def _enqueue(rec):
        try:
            queue.put_nowait(rec)
        except asyncio.QueueFull:
            pass

    unsub = store.subscribe(_enqueue)

    async def _gen():
        try:
            while True:
                rec = await queue.get()
                yield {"event": "query", "data": json.dumps(rec.to_dict())}
        except asyncio.CancelledError:
            return
        finally:
            unsub()

    return EventSourceResponse(_gen())
